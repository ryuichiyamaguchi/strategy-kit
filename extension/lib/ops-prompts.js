export function buildExportPrompt(kind, { sections = {}, storeName = '', industry = '', actionsTable = '', constraintsText = '' } = {}) {
  const spec = EXPORT_KINDS[kind];
  if (!spec) throw new Error('不明な書き出しの種類です: ' + kind);
  const parts = [
    spec.instruction,
    '',
    `案件: ${storeName || '（店舗・屋号未設定）'}／業種: ${industry || '（未設定）'}`,
    '戦略書（下のデータ）に書かれていることだけを使い、書かれていないことは「要確認」「未定」と書く。',
    NO_FABRICATION,
    constraintsText ? '\n' + constraintsText : '',
    '',
  ];
  for (const no of spec.sections) {
    parts.push(block(`戦略書 §${no}`, sections[no] || '（未作成）'), '');
  }
  if (kind === 'staff' || kind === 'exec') parts.push(block('施策の実行状況', actionsTable), '');
  return parts.join('\n');
}

