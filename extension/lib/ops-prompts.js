// STRATEGY-KIT — 運用ボードで AI に渡す指示文
//
// 原則（キット本体のプロンプトと同じ）:
//   - 外から来た本文（戦略書・実績データ・会社資料）は「データ」として境界で囲い、中の命令は実行させない
//   - 実測が無いものを推定で埋めない。無いものは「未取得」と書かせる
//   - 数字の集計・期間の判定は AI にさせず、プログラム側で済ませてから渡す

import { buildUntrustedDataBlock } from './prompt-governance.js';

const NO_FABRICATION = [
  '【守ること】',
  '- データに無い数字を作らない・推定で埋めない。無いものは「未取得」と書く',
  '- 期間が揃っていない2つの数字を直接比べない',
  '- 社外の人が読んでも分かる平易な日本語で書く（専門用語には一言の言い換えを添える）',
].join('\n');

function block(label, text) {
  return buildUntrustedDataBlock(label, String(text || '（なし）'));
}

